// Builds a plugin's src/ into dist/, the files Wings loads. Every file at the top of src/ is one entry, so
// src/main.ts becomes dist/main.js and src/sidebar.tsx becomes dist/sidebar.js, and the manifest points at them.
// Folders inside src/ hold the modules they import. Wings runs plain scripts, so each file is one bundle with
// its imports, React too. The CSS a page imports, like `import "./sidebar.css"`, becomes dist/<name>.css, and a
// page that mounts with wings-plugin-ui or wings-plugin-sdk/shell gets a dist/<name>.html written for it unless
// the plugin has its own. A plugin with no src/main.ts gets an empty dist/main.js, since Wings needs a main.
import * as esbuild from "esbuild";
import { zipSync } from "fflate";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, parse, relative } from "node:path";

const BANNER = "// Built from src/ by wings-plugin build. Edit src/, not this file.";
/** Marks a page or a stylesheet this build wrote, so it may write it again. A file without it is the plugin's own. */
const GENERATED = "Generated by wings-plugin build";
/** Where the build writes, inside the plugin folder. The manifest's `main` and pages point into it, like `dist/main.js`. */
const OUT = "dist";

/** The entries of the plugin in `dir`: `{ src, out }` for each file at the top of its src/. */
export function entries(dir) {
  const src = join(dir, "src");
  if (!existsSync(join(dir, "wings-plugin.json")) || !existsSync(src)) return [];
  return readdirSync(src, { withFileTypes: true })
    .filter((f) => f.isFile() && /\.(ts|tsx|js|jsx)$/.test(f.name) && !f.name.endsWith(".d.ts"))
    .map((f) => ({ src: join(src, f.name), out: join(dir, OUT, `${parse(f.name).name}.js`) }));
}

const escapeHtml = (s) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

/** The manifest's title for the page `dist/<name>.html`, if a sidebar, popover, view, block or settings page names it. */
function pageTitle(dir, name) {
  const { contributes = {} } = JSON.parse(readFileSync(join(dir, "wings-plugin.json"), "utf8"));
  const file = `${OUT}/${name}.html`;
  const pages = [...(contributes.sidebars ?? []), ...(contributes.views ?? []), ...(contributes.blocks ?? [])];
  const page = pages.find((p) => p.page === file) ?? pages.find((p) => p.popover?.page === file);
  if (page) return page.title;
  if (contributes.settings?.page === file) return "Settings";
  return name;
}

/** The page Wings loads for an entry that mounts with the ui shell: a mount point, its CSS and its script. */
function pageHtml(dir, name, src, hasCss) {
  return `<!doctype html>
<!-- ${GENERATED} from ${relative(dir, src)}. To write your own, replace this file with one without this line. -->
<html lang="en">
  <head>
    <meta name="generator" content="wings-plugin build" />
    <title>${escapeHtml(pageTitle(dir, name))}</title>
${hasCss ? `    <link rel="stylesheet" href="${name}.css" />\n` : ""}  </head>
  <body>
    <main id="app"></main>
    <script src="${name}.js"></script>
  </body>
</html>
`;
}

/** Whether `file` is missing or was written by this build, so the build may write it. */
const ours = (file) => !existsSync(file) || readFileSync(file, "utf8").includes(GENERATED);

/** Notes whether the bundle imports wings-plugin-ui or wings-plugin-sdk/shell, which mount the page themselves. */
function shellPlugin(seen) {
  return {
    name: "wings-shell",
    setup(build) {
      build.onResolve({ filter: /^(wings-plugin-ui|wings-plugin-sdk\/shell)$/ }, () => {
        seen.shell = true;
        // Resolve as usual.
        return undefined;
      });
    },
  };
}

/**
 * Resolves React from the plugin's folder wherever it's imported, so a page and a linked wings-plugin-ui (npm
 * link, or link: in package.json) share one React instead of the package finding its own, or none.
 */
function oneReact(dir) {
  return {
    name: "one-react",
    setup(build) {
      build.onResolve({ filter: /^react(-dom)?(\/.*)?$/ }, (args) => {
        if (args.pluginData?.fromPlugin) return undefined;
        return build.resolve(args.path, { kind: args.kind, resolveDir: dir, pluginData: { fromPlugin: true } });
      });
    },
  };
}

/**
 * Builds the plugin in `dir` into its `dist/` folder. With `check`, writes nothing and returns the outputs that
 * differ from what's on disk instead, so a release can refuse built files older than their source. With `outDir`,
 * writes the outputs there instead; a page's own HTML or CSS already in `outDir` still wins over a generated one.
 */
export async function buildPlugin(dir, { check = false, banner = BANNER, outDir = join(dir, OUT) } = {}) {
  const built = [];
  const stale = [];
  const files = [];
  for (const { src, out } of entries(dir)) {
    const { name } = parse(out);
    const seen = { shell: false };
    const result = await esbuild.build({
      entryPoints: [src],
      outfile: out,
      bundle: true,
      format: "iife",
      // WKWebView on the oldest macOS Wings supports.
      target: "safari16",
      jsx: "automatic",
      define: { "process.env.NODE_ENV": '"production"' },
      banner: { js: banner, css: `/* ${GENERATED} from src/. Edit src/, not this file. */` },
      plugins: [shellPlugin(seen), oneReact(dir)],
      legalComments: "none",
      minify: true,
      write: false,
      logLevel: "warning",
    });
    const js = result.outputFiles.find((f) => f.path.endsWith(".js"));
    const css = result.outputFiles.find((f) => f.path.endsWith(".css"));
    files.push({ name: `${name}.js`, text: js.text, owned: true });
    if (css) files.push({ name: `${name}.css`, text: css.text, owned: ours(join(outDir, `${name}.css`)) });
    if (seen.shell && ours(join(outDir, `${name}.html`))) files.push({ name: `${name}.html`, text: pageHtml(dir, name, src, Boolean(css)), owned: true });
  }
  if (!files.some((f) => f.name === "main.js")) files.push({ name: "main.js", text: `${banner}\n`, owned: true });
  const foreign = files.filter((f) => !f.owned).map((f) => f.name);
  if (foreign.length) throw new Error(`${foreign.join(", ")} would be overwritten by the CSS built from src/. Move it into src/ or rename it.`);
  if (!check) mkdirSync(outDir, { recursive: true });
  for (const { name, text } of files) {
    const file = join(outDir, name);
    if (check) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== text) stale.push(file);
    } else {
      writeFileSync(file, text);
      built.push({ file, bytes: text.length });
    }
  }
  return { built, stale };
}

/** Files at the top of a plugin folder that are for building it, not for Wings. The README stays: Wings shows it in Settings. */
const SOURCE_ONLY = /^(src|preview|node_modules|package(-lock)?\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|tsconfig.*\.json|HANDOVER.*|.*\.wings-plugin)$/;

/** Copies what the plugin ships from `from` to `to`: everything but its source, dependencies and dotfiles. */
function copyShipped(from, to, top = true) {
  for (const entry of readdirSync(from, { withFileTypes: true })) {
    if (entry.name.startsWith(".") || entry.name === "node_modules" || (top && SOURCE_ONLY.test(entry.name))) continue;
    if (entry.isDirectory()) {
      mkdirSync(join(to, entry.name));
      copyShipped(join(from, entry.name), join(to, entry.name), false);
    } else if (entry.isFile()) copyFileSync(join(from, entry.name), join(to, entry.name));
  }
}

/** Every file under `dir`, by its path inside it with `/` between folders. */
function filesIn(dir, prefix = "") {
  const out = {};
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = prefix + entry.name;
    if (entry.isDirectory()) Object.assign(out, filesIn(join(dir, entry.name), `${path}/`));
    else out[path] = new Uint8Array(readFileSync(join(dir, entry.name)));
  }
  return out;
}

/**
 * Builds the plugin in `dir` into a temporary folder with the files it ships, and zips that as `<id>.wings-plugin`
 * in `out` (the plugin folder by default), the file Wings installs. Resolves the package's path. The plugin's
 * folder gets no built files, so a plugin's own repo doesn't commit them.
 */
export async function pack(dir, { out = dir } = {}) {
  const { id } = JSON.parse(readFileSync(join(dir, "wings-plugin.json"), "utf8"));
  const tmp = mkdtempSync(join(tmpdir(), "wings-plugin-"));
  try {
    copyShipped(dir, tmp);
    await buildPlugin(dir, { outDir: join(tmp, OUT) });
    const file = join(out, `${id}.wings-plugin`);
    writeFileSync(file, zipSync(filesIn(tmp), { level: 9 }));
    return file;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}
