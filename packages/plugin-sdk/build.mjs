// Builds a plugin's src/ into dist/, the files Wings loads. The entries are src/main.ts and each file in
// src/pages/, so src/main.ts becomes dist/main.js and src/pages/sidebar.tsx becomes dist/sidebar.js, and the
// manifest points at them. Other folders in src/ hold the modules they import. Wings runs plain scripts, so each
// entry is one bundle with its imports, React too. A React page (.tsx) default-exports its component and exports
// `page` to say where it shows, and the build writes the mount that calls the matching show function of
// wings-plugin-ui. The CSS a page imports, like `import "./sidebar.css"`, becomes dist/<name>.css, and a page that
// mounts with wings-plugin-ui or wings-plugin-sdk/shell gets a dist/<name>.html written for it unless the plugin
// has its own. A plugin with no src/main.ts gets an empty dist/main.js, since Wings needs a main. A plugin whose
// manifest says `"native": true` also gets each entry built for the native app into dist/native/, and its pages built
// a second time, when it has more than one, to share one copy of React and wings-plugin-ui: dist/native/shared.js and
// dist/native/shared/. A plugin with a
// src/tools.ts gets its manifest's contributes.mcpTools written from it. Last, the manifest is checked against what
// was built, and the build fails where they disagree, so a typo doesn't wait for Wings to load the plugin.
import * as esbuild from "esbuild";
import { zipSync } from "fflate";
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, parse, relative } from "node:path";
import { manifestProblems } from "./manifest-check.mjs";
import { syncTools } from "./tools-manifest.mjs";

const BANNER = "// Built from src/ by wings-plugin build. Edit src/, not this file.";
/** Marks a page or a stylesheet this build wrote, so it may write it again. A file without it is the plugin's own. */
const GENERATED = "Generated by wings-plugin build";
/** Where the build writes, inside the plugin folder. The manifest's `main` and pages point into it, like `dist/main.js`. */
const OUT = "dist";

/** The source files directly in `folder`. */
const sourcesIn = (folder) =>
  existsSync(folder)
    ? readdirSync(folder, { withFileTypes: true })
        .filter((f) => f.isFile() && /\.(ts|tsx|js|jsx)$/.test(f.name) && !f.name.endsWith(".d.ts"))
        .map((f) => join(folder, f.name))
    : [];

/** The entries of the plugin in `dir`: `{ src, out }` for its src/main.ts and each file in its src/pages/. */
export function entries(dir) {
  const src = join(dir, "src");
  if (!existsSync(join(dir, "wings-plugin.json")) || !existsSync(src)) return [];
  return [...sourcesIn(src).filter((f) => /^main\.(ts|js)$/.test(parse(f).base)), ...sourcesIn(join(src, "pages"))].map((file) => ({ src: file, out: join(dir, OUT, `${parse(file).name}.js`) }));
}

/** The mount for a React page: its default export is the component and its `page` export says where it shows. */
const mount = (file) => `import Page, { page } from ${JSON.stringify(file)};
import { showBlock, showPopover, showSettings, showSidebar, showTab, showView } from "wings-plugin-ui";
const show = { sidebar: showSidebar, tab: showTab, view: showView, block: showBlock, settings: showSettings, popover: showPopover }[page.place];
if (!show) throw new Error("page.place is sidebar, tab, view, block, settings or popover, not " + page.place);
show(<Page />, { fill: page.fill });
`;

const escapeHtml = (s) => s.replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

/** The manifest's title for the page `dist/<name>.html`, if a sidebar, popover, view, block or settings page names it. */
function pageTitle(dir, name) {
  const { contributes = {} } = JSON.parse(readFileSync(join(dir, "wings-plugin.json"), "utf8"));
  const file = `${OUT}/${name}.html`;
  const pages = [...(contributes.sidebars ?? []), ...(contributes.views ?? []), ...(contributes.blocks ?? [])];
  const page = pages.find((p) => p.page === file) ?? pages.find((p) => p.popover?.page === file);
  if (page) return page.title;
  if (contributes.settings?.page === file) return "Settings";
  return name;
}

/** The page Wings loads for an entry that mounts with the ui shell: a mount point, its CSS and its script. */
function pageHtml(dir, name, src, hasCss) {
  return `<!doctype html>
<!-- ${GENERATED} from ${relative(dir, src)}. To write your own, replace this file with one without this line. -->
<html lang="en">
  <head>
    <meta name="generator" content="wings-plugin build" />
    <title>${escapeHtml(pageTitle(dir, name))}</title>
${hasCss ? `    <link rel="stylesheet" href="${name}.css" />\n` : ""}  </head>
  <body>
    <main id="app"></main>
    <script src="${name}.js"></script>
  </body>
</html>
`;
}

/** Whether `file` is missing or was written by this build, so the build may write it. */
const ours = (file) => !existsSync(file) || readFileSync(file, "utf8").includes(GENERATED);

/** Notes whether the bundle imports wings-plugin-ui or wings-plugin-sdk/shell, which mount the page themselves. */
function shellPlugin(seen) {
  return {
    name: "wings-shell",
    setup(build) {
      build.onResolve({ filter: /^(wings-plugin-ui|wings-plugin-sdk\/shell)$/ }, () => {
        seen.shell = true;
        // Resolve as usual.
        return undefined;
      });
    },
  };
}

/**
 * Resolves React from the plugin's folder wherever it's imported, so a page and a linked wings-plugin-ui (npm
 * link, or link: in package.json) share one React instead of the package finding its own, or none.
 */
function oneReact(dir) {
  return {
    name: "one-react",
    setup(build) {
      build.onResolve({ filter: /^react(-dom)?(\/.*)?$/ }, (args) => {
        if (args.pluginData?.fromPlugin) return undefined;
        return build.resolve(args.path, { kind: args.kind, resolveDir: dir, pluginData: { fromPlugin: true } });
      });
    },
  };
}

/**
 * The mount for a native page: its default export is the component, and the app decides where it shows. `fill` goes
 * along as the browser mount's does, except on a block, whose `showBlock` takes no options.
 */
const nativeMount = (file) => `import Page, { page } from ${JSON.stringify(file)};
import { mount } from "wings-plugin-ui/native";
mount(<Page />, { fill: page.place !== "block" && page.fill === true });
`;

/** Points `wings-plugin-ui` at its native build, which draws a smaller set of components with the same names and props. */
function nativeUi(dir) {
  return {
    name: "wings-native-ui",
    setup(build) {
      build.onResolve({ filter: /^wings-plugin-ui$/ }, (args) => build.resolve("wings-plugin-ui/native", { kind: args.kind, resolveDir: dir }));
    },
  };
}

/** The line to print for each error esbuild collected, with a component the native renderer lacks named as one. */
function nativeProblems({ errors }) {
  return errors.map(({ text, location }) => {
    const at = location ? `${location.file}:${location.line}: ` : "";
    const missing = /^No matching export in "[^"]*" for import "([^"]+)"/.exec(text)?.[1];
    if (missing) return `${at}${missing} isn't in wings-plugin-ui/native, which draws a smaller set of components than wings-plugin-ui (see its native.d.ts). Use ones it has, or take "native" out of wings-plugin.json until the page is ported.`;
    return `${at}${text}`;
  });
}

/** What a page built to share them gets each of React, its JSX runtime and wings-plugin-ui from: its instance of dist/native/shared.js. */
const SHARED = { react: "react", "react/jsx-runtime": "jsx", "wings-plugin-ui": "ui", "wings-plugin-ui/native": "ui" };

/** Points the packages in SHARED at the page's instance of the library, `__wingsShared`, which the app gives it. */
function sharedLibrary() {
  return {
    name: "wings-shared",
    setup(build) {
      build.onResolve({ filter: /^(react|react\/jsx-runtime|wings-plugin-ui|wings-plugin-ui\/native)$/ }, (args) => ({ path: args.path, namespace: "wings-shared" }));
      build.onLoad({ filter: /.*/, namespace: "wings-shared" }, (args) => ({ contents: `module.exports = __wingsShared.${SHARED[args.path]};`, loader: "js" }));
    },
  };
}

/**
 * dist/native/shared.js: React, its JSX runtime and what the pages use of wings-plugin-ui/native (`names`, or all of it
 * when that's null), as the plugin has them installed, defining `__wingsLib`. The native app compiles it once for all
 * the plugin's open pages and runs it again for each page that shares it, so each has its own React state while the
 * code is held once. Each run builds every module-level table the library has, so it holds only what pages use: all
 * of wings-plugin-ui costs each page 250 KB of the engine's heap, and a page's share 170 KB (measured).
 */
const librarySource = (names) => `import * as react from "react";
import * as jsx from "react/jsx-runtime";
${names ? `import { ${names.join(", ")} } from "wings-plugin-ui/native";\nexport const ui = { ${names.join(", ")} };` : `import * as ui from "wings-plugin-ui/native";\nexport { ui };`}
export { react, jsx };
`;

/** The names the native pages `pages` import from wings-plugin-ui and the mount uses, or null when one imports it whole. */
async function uiNames(dir, pages) {
  const names = new Set(["mount"]);
  for (const { src } of pages) {
    const { outputFiles } = await esbuild.build({
      entryPoints: [src],
      bundle: true,
      format: "esm",
      platform: "neutral",
      jsx: "automatic",
      mainFields: ["module", "main"],
      loader: { ".css": "empty" },
      define: { "process.env.NODE_ENV": '"production"', WINGS_NATIVE: "true" },
      external: ["react", "react/*", "wings-plugin-ui", "wings-plugin-ui/*"],
      write: false,
      logLevel: "silent",
    });
    // esbuild writes each external's imports as one statement, with only the names the page keeps.
    for (const [, imported] of outputFiles[0].text.matchAll(/^import (.+) from "wings-plugin-ui(?:\/native)?";$/gm)) {
      const named = /^\{([^}]*)\}$/.exec(imported.trim());
      if (!named) return null;
      for (const part of named[1].split(",")) names.add(part.trim().split(/\s+as\s+/)[0]);
    }
  }
  return [...names].sort();
}

/** The first line of a page built to share dist/native/shared.js, before the SHA-256 of that file. The app runs it only with that file. */
const SHARED_MARKER = "// wings-shared ";

/**
 * The script for the native app that `src` builds to: one classic script, like the browser build's, but for a JS
 * engine with no DOM. `wings-plugin-ui` is `wings-plugin-ui/native` here, CSS imports are dropped (the app draws
 * the page itself), and a page mounts with that package's `mount`. Fails naming each component the page imports
 * that the native renderer doesn't have.
 */
async function buildNative(dir, src, banner, { shared = false, library = null } = {}) {
  const page = dirname(src) === join(dir, "src", "pages");
  if (page && !/\.[jt]sx$/.test(src)) throw new Error(`${relative(dir, src)}: a native page is a React page that default-exports its component, like src/pages/sidebar.tsx. Write this one that way, or take "native" out of wings-plugin.json.`);
  const entry = library
    ? { stdin: { contents: librarySource(library.names), resolveDir: dir, sourcefile: "dist/native/shared.js", loader: "js" }, globalName: "__wingsLib" }
    : page
      ? { stdin: { contents: nativeMount(src), resolveDir: dir, sourcefile: `${relative(dir, src)} (native mount)`, loader: "tsx" } }
      : { entryPoints: [src] };
  try {
    const result = await esbuild.build({
      ...entry,
      bundle: true,
      format: "iife",
      platform: "neutral",
      // QuickJS runs it.
      target: "es2022",
      jsx: "automatic",
      mainFields: ["module", "main"],
      loader: { ".css": "empty" },
      define: { "process.env.NODE_ENV": '"production"', WINGS_NATIVE: "true" },
      banner: { js: banner },
      plugins: [...(shared ? [sharedLibrary()] : []), nativeUi(dir), oneReact(dir)],
      legalComments: "none",
      minify: true,
      write: false,
      logLevel: "silent",
    });
    return result.outputFiles[0].text;
  } catch (error) {
    if (!Array.isArray(error.errors)) throw error;
    throw new Error(nativeProblems(error).join("\n"));
  }
}

/**
 * Builds the plugin in `dir` into its `dist/` folder. With `check`, writes nothing and returns the outputs that
 * differ from what's on disk instead, so a release can refuse built files that no longer match their source. With `outDir`,
 * writes the outputs there instead; a page's own HTML or CSS already in `outDir` still wins over a generated one.
 * The manifest with the tools from src/tools.ts goes to `manifestDir`, the plugin folder by default. Throws a line for
 * each place that manifest and the built code disagree. A manifest with `"native": true` also gets `native/main.js`
 * and `native/<page>.js` in `outDir`, for the native app, and with two pages or more `native/shared.js` and `native/shared/<page>.js`,
 * the pages again sharing that one copy of React and wings-plugin-ui.
 */
export async function buildPlugin(dir, { check = false, banner = BANNER, outDir = join(dir, OUT), manifestDir = dir } = {}) {
  const built = [];
  const stale = [];
  const files = [];
  const nativeFiles = [];
  const native = JSON.parse(readFileSync(join(dir, "wings-plugin.json"), "utf8")).native === true;
  for (const { src, out } of entries(dir)) {
    const { name } = parse(out);
    const seen = { shell: false };
    const result = await esbuild.build({
      ...(/\.[jt]sx$/.test(src) ? { stdin: { contents: mount(src), resolveDir: dir, sourcefile: `${relative(dir, src)} (mount)`, loader: "tsx" } } : { entryPoints: [src] }),
      outfile: out,
      bundle: true,
      format: "iife",
      // WKWebView on the oldest macOS Wings supports.
      target: "safari16",
      jsx: "automatic",
      define: { "process.env.NODE_ENV": '"production"', WINGS_NATIVE: "false" },
      banner: { js: banner, css: `/* ${GENERATED} from src/. Edit src/, not this file. */` },
      plugins: [shellPlugin(seen), oneReact(dir)],
      legalComments: "none",
      minify: true,
      write: false,
      logLevel: "warning",
    });
    const js = result.outputFiles.find((f) => f.path.endsWith(".js"));
    const css = result.outputFiles.find((f) => f.path.endsWith(".css"));
    files.push({ name: `${name}.js`, text: js.text, owned: true });
    if (css) files.push({ name: `${name}.css`, text: css.text, owned: ours(join(outDir, `${name}.css`)) });
    if (seen.shell && ours(join(outDir, `${name}.html`))) files.push({ name: `${name}.html`, text: pageHtml(dir, name, src, Boolean(css)), owned: true });
    if (native) nativeFiles.push({ name: `native/${name}.js`, text: await buildNative(dir, src, banner) });
  }
  // Each page again, sharing one React and wings-plugin-ui with the others: the app runs these when it can and the
  // ones above, which carry their own, when it can't, as a Wings from before this does. With one page there is no
  // other to share with, and the library's own cost makes that page bigger (measured: 1.4 MB against 1.0 MB).
  const pages = native ? entries(dir).filter(({ src }) => dirname(src) === join(dir, "src", "pages")) : [];
  if (pages.length > 1) {
    if (pages.some(({ out }) => parse(out).name === "shared")) throw new Error(`${relative(process.cwd(), join(dir, "src", "pages"))}: a native page can't be called shared, as dist/native/shared.js is the React its pages share. Rename it.`);
    const library = await buildNative(dir, join(dir, "src", "shared.js"), banner, { library: { names: await uiNames(dir, pages) } });
    const hash = createHash("sha256").update(library).digest("hex");
    nativeFiles.push({ name: "native/shared.js", text: library });
    for (const { src, out } of pages) nativeFiles.push({ name: `native/shared/${parse(out).name}.js`, text: `${SHARED_MARKER}${hash}\n${await buildNative(dir, src, banner, { shared: true })}` });
  }
  if (!files.some((f) => f.name === "main.js")) files.push({ name: "main.js", text: `${banner}\n`, owned: true });
  if (native && !nativeFiles.some((f) => f.name === "native/main.js")) nativeFiles.push({ name: "native/main.js", text: `${banner}\n` });
  const foreign = files.filter((f) => !f.owned).map((f) => f.name);
  if (foreign.length) throw new Error(`${foreign.join(", ")} would be overwritten by the CSS built from src/. Move it into src/ or rename it.`);
  if (!check) mkdirSync(outDir, { recursive: true });
  for (const { name, text } of [...files, ...nativeFiles]) {
    const file = join(outDir, name);
    if (check) {
      if (!existsSync(file) || readFileSync(file, "utf8") !== text) stale.push(file);
    } else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, text);
      built.push({ file, bytes: text.length });
    }
  }
  const tools = await syncTools(dir, { check, outDir: manifestDir });
  const manifest = JSON.parse(readFileSync(join(manifestDir, "wings-plugin.json"), "utf8"));
  const problems = manifestProblems(manifest, { root: manifestDir, built: files.map(({ name, text }) => ({ file: `${OUT}/${name}`, text })), main: `${OUT}/main.js` });
  if (problems.length) throw new Error(problems.map((problem) => `${relative(process.cwd(), join(dir, "wings-plugin.json"))}: ${problem}`).join("\n"));
  return { built: [...built, ...tools.built], stale: [...stale, ...tools.stale] };
}

/** Files at the top of a plugin folder that are for building it, not for Wings. The README stays: Wings shows it in Settings. */
const SOURCE_ONLY = /^(src|preview|node_modules|package(-lock)?\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?|tsconfig.*\.json|HANDOVER.*|.*\.wings-plugin|rust|target|Cargo\.(toml|lock))$/;

/** Copies what the plugin ships from `from` to `to`: everything but its source, dependencies and dotfiles. */
function copyShipped(from, to, top = true) {
  for (const entry of readdirSync(from, { withFileTypes: true })) {
    if (entry.name.startsWith(".") || entry.name === "node_modules" || (top && SOURCE_ONLY.test(entry.name))) continue;
    if (entry.isDirectory()) {
      mkdirSync(join(to, entry.name));
      copyShipped(join(from, entry.name), join(to, entry.name), false);
    } else if (entry.isFile()) copyFileSync(join(from, entry.name), join(to, entry.name));
  }
}

/** Every file under `dir`, by its path inside it with `/` between folders. */
function filesIn(dir, prefix = "") {
  const out = {};
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = prefix + entry.name;
    if (entry.isDirectory()) Object.assign(out, filesIn(join(dir, entry.name), `${path}/`));
    else out[path] = new Uint8Array(readFileSync(join(dir, entry.name)));
  }
  return out;
}

/**
 * Builds the plugin in `dir` into a temporary folder with the files it ships, and zips that as `<id>.wings-plugin`
 * in `out` (the plugin folder by default), the file Wings installs. Resolves the package's path. The plugin's
 * folder gets no built files, so a plugin's own repo doesn't commit them.
 *
 * A plugin written in Rust alone has no `src/`: there is nothing here to build, and its package is what it ships,
 * with the WebAssembly frames its own build put in `dist/native/`. Its Rust source and build folder stay out.
 */
export async function pack(dir, { out = dir } = {}) {
  const { id, main } = JSON.parse(readFileSync(join(dir, "wings-plugin.json"), "utf8"));
  const tmp = mkdtempSync(join(tmpdir(), "wings-plugin-"));
  try {
    copyShipped(dir, tmp);
    if (existsSync(join(dir, "src"))) await buildPlugin(dir, { outDir: join(tmp, OUT), manifestDir: tmp });
    else if (!existsSync(join(tmp, main))) throw new Error(`${main} is missing. Build the plugin's Rust frames first.`);
    const file = join(out, `${id}.wings-plugin`);
    writeFileSync(file, zipSync(filesIn(tmp), { level: 9 }));
    return file;
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
}
